**The Universal Pattern:**
Joseph Campbell documented across 300+ mythological traditions what he called the Monomyth — the Hero's Journey. At its core is always the same sequence:

**1. The Call** — The ordinary world is disrupted. A threshold must be crossed.
**2. The Descent** — The hero goes underground, into the underworld, into darkness and death.
**3. The Transformation** — In the depths, something essential changes. The old self cannot survive.
**4. The Return** — The hero returns with something the community needs. Not the same person who left.

This is not a story structure. It is the universal description of the initiation process — the psychological and spiritual death that precedes genuine transformation.

**The Mystery School Initiations:**
The ancient Greek mystery schools at Eleusis initiated hundreds of thousands of people over 2,000 years. The initiation process included:
- A period of ritual fasting and purification
- A ceremonial "death" — complete darkness, disorientation, sensory dissolution
- An experience of descent — the initiates reported feeling they had died
- An emergence — described universally as a rebirth into a different quality of awareness

