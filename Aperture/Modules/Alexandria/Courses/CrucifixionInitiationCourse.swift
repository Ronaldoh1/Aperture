You have already been crucified. You may not have recognized it.

**What a Personal Crucifixion Looks Like:**
A crucifixion is any experience in which an identity you had built — a story about who you were, a role you occupied, a relationship that defined you, a belief system that organized your world — is destroyed without your consent.

It feels like:
- The loss of a relationship you defined yourself through
