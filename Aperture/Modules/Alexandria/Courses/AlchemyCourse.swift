*The shadow:* People resist calcination indefinitely — through distraction, addiction, performance, or doubling down on the false structures. This extends the suffering without ending the process.

**STAGE 2 — DISSOLUTION (💧 Water)**
*Emotions flood in.*

If calcination is fire, dissolution is water. What the fire loosened, the water moves. Everything suppressed, everything stored, everything that was held in the body below conscious awareness begins to surface.

This is the stage of emotional processing — grief, rage, terror, despair — that follows the initial crisis. It is often confused with regression or breakdown. It is neither. It is material coming into consciousness for the first time.

Dissolution feels like: crying that has no clear source, emotional flooding, revisiting old wounds, feeling everything you've been successfully not feeling for years.

*What is dissolving:* The suppression patterns, the emotional armoring, the stories built to make the pain bearable rather than integrated.

*The shadow:* Getting lost in the dissolution — identifying with the emotions rather than witnessing them. The goal is to let the water flow, not to become the water.

