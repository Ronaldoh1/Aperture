**The Common Elements Across Traditions:**

**1. The Turning Inward (Metanoia)**
The Greek word translated as "repentance" in the New Testament is *metanoia* — literally "a change of mind" or "turning around the direction of consciousness." Not guilt. Not self-punishment. A 180-degree reorientation of where you're looking.

Instead of seeking the divine outside — in institutions, in external authorities, in future events — you turn the gaze around. Inward. Downward. Into the present moment, the body, the breath, the immediate field of your own awareness.

**2. Kenosis — Emptying**
The mystical Christian tradition uses the word *kenosis* (Greek: "self-emptying") to describe what Philippians 2:7 says about Jesus: he "emptied himself." The ego — with its preferences, defenses, narratives, and agendas — must be emptied enough to allow a larger intelligence to move through.

This is not destruction. It's availability. A full cup cannot receive more. The Christos fills what the ego empties.

