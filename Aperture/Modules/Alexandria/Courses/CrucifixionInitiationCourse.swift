Carl Jung documented that the psyche goes through a process of individuation — a lifelong sequence of identity deaths and rebirths. Each time a persona (a role, a mask, a story) that has served its purpose is stripped away, the underlying Self can emerge more completely.

The persona is not the Self. The persona is what the Self built for a particular phase of life. When the phase ends, the persona must die — often painfully, often before the individual is ready — so that the next phase can begin.

