**STAGE 1 — CALCINATION (🔥 Fire)**
*The burning of the ego's fixed structures.*

Calcination is the reduction of a substance to ash through sustained heat. In inner alchemy, it is the crisis that shatters who you thought you were.

This is the awakening trigger: a betrayal, a loss, a diagnosis, a collapse of the worldview you'd built your identity on. The system is not broken. The system is working exactly as designed. The heat is necessary — the false structures cannot be transformed; they must first be reduced to their elemental components.

